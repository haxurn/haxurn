const GENERATED_DIR = './profile/generated';

export function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function picture({ name, alt }, width, version) {
  const src = (theme) => `${GENERATED_DIR}/${name}-${theme}.svg?v=${version}`;
  return `<picture><source media="(prefers-color-scheme: dark)" srcset="${src('dark')}">`
    + `<source media="(prefers-color-scheme: light)" srcset="${src('light')}">`
    + `<img src="${src('light')}" width="${width}" alt="${escapeHtml(alt)}"></picture>`;
}

function linked(panel, width, version) {
  return `<a href="${escapeHtml(panel.url)}">${picture(panel, width, version)}</a>`;
}

/** Panels in one row have no whitespace between them, or GitHub would wrap the last one. */
function row(panels, version) {
  const width = `${100 / panels.length}%`;
  return panels.map((panel) => linked(panel, width, version)).join('');
}

/** GitHub strips scripts, so `details` is the only switch a profile README can have. */
function modeSwitch({ label, role, isOpen, ...panel }, version) {
  return `<details${isOpen ? ' open' : ''}>\n<summary><b>${escapeHtml(label)}</b> · ${escapeHtml(role)}</summary>\n\n`
    + `<p align="center">${picture(panel, '100%', version)}</p>\n</details>`;
}

export function buildReadme({ version, header, links, modes, activity, cards, ledger }) {
  return [
    '<!-- Generated by scripts/build-profile.mjs. Edit profile.config.json, not this file. -->',
    `<p align="center">${picture(header, '100%', version)}</p>`,
    `<p align="center">${row(links, version)}</p>`,
    ...modes.map((mode) => modeSwitch(mode, version)),
    `<p align="center">${linked(activity, '100%', version)}</p>`,
    `<p align="center">${row(cards, version)}</p>`,
    `<p align="center">${linked(ledger, '100%', version)}</p>`,
    '',
  ].join('\n\n');
}
